"""
scripts/false_alarm_report.py — False-Alarm Rate Profiler & Category Benchmark Tool.

Directly addresses Roadmap Item D (Measure False-Alarm Rate):
Replays surveillance video feeds or evaluates historical events to compute:
  - Observation duration (hours)
  - Alert frequency per hour by category (weapon, breach, loiter, posture, running)
  - False-alarm rate metrics to validate operational thresholds for border submission.

Usage:
    python scripts/false_alarm_report.py --sample
    python scripts/false_alarm_report.py --db data/events.db --hours 24
"""
from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path
from typing import Dict, List

# Add backend/app to path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))


def generate_benchmark_report(
    events: List[Dict],
    duration_hours: float,
    stream_count: int = 1,
    ground_truth_threats: int = 0,
) -> str:
    """Generate a markdown benchmark report of alerts per hour by category."""
    duration_hours = max(0.01, duration_hours)
    total_events = len(events)

    cat_counts: Dict[str, int] = {}
    sev_counts: Dict[str, int] = {}

    for ev in events:
        c = str(ev.get("category", "other")).lower()
        s = str(ev.get("severity", "Info")).capitalize()
        cat_counts[c] = cat_counts.get(c, 0) + 1
        sev_counts[s] = sev_counts.get(s, 0) + 1

    alerts_per_hour = total_events / duration_hours
    alerts_per_stream_hour = alerts_per_hour / max(1, stream_count)

    false_alarms = max(0, total_events - ground_truth_threats)
    far_pct = (false_alarms / total_events * 100.0) if total_events > 0 else 0.0

    lines = [
        "# 📊 IBVAP False-Alarm & Category Rate Profiling Report",
        "",
        f"**Date Generated:** {time.strftime('%Y-%m-%d %H:%M:%SZ', time.gmtime())}  ",
        f"**Observation Window:** {duration_hours:.2f} hours  ",
        f"**Monitored Camera Streams:** {stream_count}  ",
        f"**Total Events Evaluated:** {total_events}  ",
        "",
        "---",
        "",
        "## 1. Aggregate Frequency Metrics",
        "",
        f"- **Alerts Per Hour (Total):** {alerts_per_hour:.2f} / hr",
        f"- **Alerts Per Stream-Hour:** {alerts_per_stream_hour:.2f} / stream-hr",
        f"- **Estimated False Positive Rate (FAR):** {far_pct:.1f}% (Ground truth threats: {ground_truth_threats})",
        "",
        "## 2. Category Breakdown & Rate Analysis",
        "",
        "| Category | Event Count | Rate (Alerts / Hr) | Severity Distribution |",
        "|---|---|---|---|",
    ]

    for cat, count in sorted(cat_counts.items(), key=lambda x: -x[1]):
        rate = count / duration_hours
        lines.append(f"| `{cat}` | {count} | {rate:.2f} | {count / total_events * 100:.1f}% |")

    lines.extend([
        "",
        "## 3. Threshold Guidance & Optimization",
        "",
        "- If running/group alerts exceed 2.0/hr in peaceful corridors, raise `behaviour.group_distance_bh` threshold.",
        "- If posture alerts exceed 1.0/hr, ensure camera mounting height is at least 3m to prevent foreshortening errors.",
        "",
        "---",
        "*Generated by IBVAP False-Alarm Profiler (scripts/false_alarm_report.py)*",
    ])

    return "\n".join(lines)


def sample_benchmark() -> tuple[list[dict], float, int]:
    """Synthetic benchmark dataset for evaluation."""
    events = [
        {"category": "plate", "severity": "Info"},
        {"category": "plate", "severity": "Info"},
        {"category": "loiter", "severity": "Medium"},
        {"category": "running", "severity": "Medium"},
        {"category": "intrusion", "severity": "High"},
        {"category": "weapon", "severity": "Critical"},
    ]
    return events, 4.0, 2


def main() -> None:
    parser = argparse.ArgumentParser(description="IBVAP False-Alarm Rate Profiler")
    parser.add_argument("--db", help="Path to events.db")
    parser.add_argument("--hours", type=float, default=12.0, help="Observation duration in hours")
    parser.add_argument("--streams", type=int, default=1, help="Number of concurrent camera streams")
    parser.add_argument("--threats", type=int, default=1, help="Known ground truth threats in dataset")
    parser.add_argument("--sample", action="store_true", help="Generate benchmark from demonstration dataset")
    parser.add_argument("--out", help="Output report markdown path")
    args = parser.parse_args()

    if args.sample or not args.db:
        events, duration, streams = sample_benchmark()
    else:
        from ibvap.event_store import EventStore
        db_path = Path(args.db)
        if not db_path.is_file():
            print(f"Error: Database {args.db} does not exist.")
            sys.exit(1)
        store = EventStore(str(db_path))
        since = time.time() - (args.hours * 3600.0)
        events = store.query(limit=5000, since=since, include_unconfirmed=True)
        duration = args.hours
        streams = args.streams

    report = generate_benchmark_report(
        events=events,
        duration_hours=duration,
        stream_count=streams,
        ground_truth_threats=args.threats,
    )

    if args.out:
        out_p = Path(args.out)
        out_p.parent.mkdir(parents=True, exist_ok=True)
        out_p.write_text(report, encoding="utf-8")
        print(f"Benchmark report saved to {out_p.resolve()}")
    else:
        print(report)


if __name__ == "__main__":
    main()
